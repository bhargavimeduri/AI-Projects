# ============================================================
# CELL 2.1 — IMAGE QUALITY FILTER
# Automatically removes corrupt, too dark, too bright,
# or too blurry images before training
# ============================================================

import cv2
import numpy as np
import os
from PIL import Image

def assess_image_quality(image_path):
    """
    Returns (status, reason)
    status: 'GOOD' or 'BAD'
    """
    try:
        # Try opening with PIL first (catches corrupt files)
        pil_img = Image.open(image_path)
        pil_img.verify()

        # Reload after verify (verify closes the file)
        img = cv2.imread(image_path)
        if img is None:
            return 'BAD', 'Cannot read file'

        # Check minimum size
        h, w = img.shape[:2]
        if h < 64 or w < 64:
            return 'BAD', f'Too small ({w}x{h})'

        # Check brightness
        gray       = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
        brightness = np.mean(gray)
        if brightness < 15:
            return 'BAD', f'Too dark (brightness={brightness:.1f})'
        if brightness > 245:
            return 'BAD', f'Too bright/overexposed (brightness={brightness:.1f})'

        # Check blur using Laplacian variance
        blur_score = cv2.Laplacian(gray, cv2.CV_64F).var()
        if blur_score < 10:
            return 'BAD', f'Too blurry (score={blur_score:.1f})'

        return 'GOOD', f'OK (brightness={brightness:.1f}, blur={blur_score:.1f})'

    except Exception as e:
        return 'BAD', f'Corrupt file: {str(e)[:50]}'


def clean_folder(folder_path, folder_name):
    exts = ('.jpg', '.jpeg', '.png', '.webp', '.bmp')
    images = [f for f in os.listdir(folder_path)
              if f.lower().endswith(exts)]
    good, bad = 0, 0
    bad_files = []
    for fname in images:
        fpath  = os.path.join(folder_path, fname)
        status, reason = assess_image_quality(fpath)
        if status == 'BAD':
            bad += 1
            bad_files.append((fname, reason))
        else:
            good += 1
    return good, bad, bad_files


