"""### Cell 4.2 — Build EfficientNetB3 Classifier"""

# ============================================================
# CELL 4.2 — BUILD EFFICIENTNETB3 TIGER TYPE CLASSIFIER
# Uses Transfer Learning — borrows knowledge from a model
# already trained on 1.2 million images
# ============================================================

import tensorflow as tf
from tensorflow.keras.applications import EfficientNetB3
from tensorflow.keras import layers, models, regularizers

# Load EfficientNetB3 pretrained on ImageNet
# include_top=False removes the final classification layer
# so we can add our own 5-class tiger type layer
base_model = EfficientNetB3(
    input_shape = (300, 300, 3),
    include_top = False,
    weights     = 'imagenet'
)

# Freeze the base model
# We keep Google's learned knowledge intact
# and only train our new top layers
base_model.trainable = False

# Build the complete model
inputs = tf.keras.Input(shape=(300, 300, 3))
x      = base_model(inputs, training=False)
x      = layers.GlobalAveragePooling2D()(x)
x      = layers.BatchNormalization()(x)
x      = layers.Dense(
             512,
             activation='relu',
             kernel_regularizer=regularizers.l2(0.001)
         )(x)
x      = layers.Dropout(0.5)(x)
x      = layers.Dense(
             256,
             activation='relu',
             kernel_regularizer=regularizers.l2(0.001)
         )(x)
x      = layers.Dropout(0.4)(x)
outputs = layers.Dense(NUM_CLASSES, activation='softmax')(x)

classifier_model = tf.keras.Model(inputs, outputs)

# Compile with AdamW optimizer
classifier_model.compile(
    optimizer = tf.keras.optimizers.AdamW(learning_rate=0.001),
    loss      = 'categorical_crossentropy',
    metrics   = ['accuracy',
                 tf.keras.metrics.TopKCategoricalAccuracy(
                     k=2, name='top2_accuracy')]
)

# Print model summary
total_params     = classifier_model.count_params()
trainable_params = sum([tf.size(w).numpy()
                        for w in classifier_model.trainable_weights])

