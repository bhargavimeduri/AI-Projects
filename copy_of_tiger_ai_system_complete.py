def preprocess_for_camera_trap(image_path):
    """
    Handles common camera trap image issues:
    - IR grayscale night shots → converts to RGB
    - Dark images → brightness boost
    - Low contrast → contrast enhancement
    """
    img = Image.open(image_path)

    # Convert IR grayscale to RGB
    if img.mode != 'RGB':
        img = img.convert('RGB')

    img_array  = np.array(img)
    brightness = np.mean(img_array)

    # Auto brightness boost for dark images
    if brightness < 60:
        from PIL import ImageEnhance
        enhancer = ImageEnhance.Brightness(img)
        img      = enhancer.enhance(2.0)
        enhancer = ImageEnhance.Contrast(img)
        img      = enhancer.enhance(1.5)
    elif brightness < 100:
        from PIL import ImageEnhance
        enhancer = ImageEnhance.Brightness(img)
        img      = enhancer.enhance(1.4)
        enhancer = ImageEnhance.Contrast(img)
        img      = enhancer.enhance(1.2)

    return img


def classify_tiger_crop(crop_array):
    """
    Takes a cropped tiger image (numpy array)
    Returns (tiger_type, confidence)
    """
    # Resize to EfficientNetB3 input size
    crop_pil    = Image.fromarray(crop_array)
    crop_resize = crop_pil.resize((300, 300))
    crop_norm   = np.array(crop_resize) / 255.0
    crop_batch  = np.expand_dims(crop_norm, axis=0)

    # Predict
    predictions = classifier_model.predict(crop_batch, verbose=0)
    pred_idx    = np.argmax(predictions[0])
    confidence  = float(predictions[0][pred_idx])
    tiger_type  = CLASS_NAMES[pred_idx]

    return tiger_type, confidence, predictions[0]


def analyze_image(image_path,
                  conf_threshold = 0.35,
                  iou_threshold  = 0.5,
                  show_result    = True):
    """
    Main pipeline function.
    Takes an image path and returns complete tiger analysis.

    Parameters:
    - image_path    : path to the image file
    - conf_threshold: YOLO confidence threshold (0.0 to 1.0)
                      increase if seeing too many false detections
                      decrease if missing real tigers
    - iou_threshold : overlap threshold for duplicate removal
                      increase if seeing duplicate boxes on same tiger
    - show_result   : whether to display the annotated image

    Returns: dict with detection results
    """
    filename = os.path.basename(image_path)

    # ── STEP 1: Image Quality Check ────────────────────────
    # The custom preprocessing was interfering with YOLO's detection.
    # YOLO will now handle its own image loading and initial preprocessing.
    # We still run preprocess_for_camera_trap to get img_pil for subsequent
    # steps like classification and display, but YOLO will operate on the raw image path.
    original_img_pil = Image.open(image_path) # Load original for display/further processing
    img_pil          = preprocess_for_camera_trap(image_path)
    img_array        = np.array(img_pil)
    brightness       = np.mean(img_array)

    quality_issues = []
    if brightness < 20:
        quality_issues.append('Very dark image')
    if brightness > 240:
        quality_issues.append('Overexposed image')

    gray       = cv2.cvtColor(img_array, cv2.COLOR_RGB2GRAY)
    blur_score = cv2.Laplacian(gray, cv2.CV_64F).var()
    if blur_score < 10:
        quality_issues.append(f'Very blurry (score={blur_score:.1f})')

    # ── STEP 2: Tiger Detection with YOLO ──────────────────
    results = yolo_model(
        image_path, # Changed from img_pil to image_path to use YOLO's native loading
        conf    = conf_threshold,
        iou     = iou_threshold,
        verbose = False
    )

    detections  = []
    result      = results[0]
    boxes       = result.boxes
    annotated   = np.array(original_img_pil.copy()) # Use original image for annotation

    # ── STEP 3: Classify Each Detected Tiger ───────────────
    for i, box in enumerate(boxes):
        # Get bounding box coordinates
        x1, y1, x2, y2 = map(int, box.xyxy[0].tolist())
        det_conf        = float(box.conf[0])

        # Crop the tiger from the image
        # Add small padding around the box
        pad  = 10
        h, w = img_array.shape[:2]
        cx1  = max(0, x1 - pad)
        cy1  = max(0, y1 - pad)
        cx2  = min(w, x2 + pad)
        cy2  = min(h, y2 + pad)
        # Use img_array for classification as it has preprocessing for quality (brightness/contrast)
        crop = img_array[cy1:cy2, cx1:cx2]

        # Classify the cropped tiger
        if crop.size > 0:
            tiger_type, type_conf, all_probs = classify_tiger_crop(crop)
        else:
            tiger_type, type_conf = 'unknown', 0.0
            all_probs = np.zeros(NUM_CLASSES)

        # Determine detection quality
        area        = (x2 - x1) * (y2 - y1)
        total_area  = img_array.shape[0] * img_array.shape[1]
        area_ratio  = area / total_area

        if area_ratio > 0.15:
            visibility = 'full'
        elif area_ratio > 0.05:
            visibility = 'partial'
        else:
            visibility = 'trace'

        detection = {
            'tiger_id'    : i + 1,
            'type'        : tiger_type,
            'display_name': TYPE_DISPLAY_NAMES.get(tiger_type, tiger_type),
            'det_conf'    : det_conf,
            'type_conf'   : type_conf,
            'visibility'  : visibility,
            'bbox'        : (x1, y1, x2, y2),
            'all_probs'   : all_probs
        }
        detections.append(detection)

        # ── Draw on image ──────────────────────────────────
        color = BOX_COLORS.get(tiger_type, (0, 255, 0))

        # Draw bounding box
        cv2.rectangle(annotated, (x1, y1), (x2, y2), color, 3)

        # Draw label background
        label     = f'Tiger {i+1}: {TYPE_DISPLAY_NAMES.get(tiger_type, tiger_type)}'
        sub_label = f'Det:{det_conf:.0%} Type:{type_conf:.0%} [{visibility}]'

        (lw, lh), _ = cv2.getTextSize(label, cv2.FONT_HERSHEY_SIMPLEX, 0.6, 2)
        cv2.rectangle(annotated,
                      (x1, y1 - lh - 25),
                      (x1 + max(lw, 200), y1),
                      color, -1)

        # Draw text
        text_color = (0, 0, 0) if tiger_type in ['white_tiger',
                                                  'snow_white_tiger',
                                                  'golden_tiger'] else (255, 255, 255)
        cv2.putText(annotated, label,
                    (x1 + 3, y1 - 13),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.55, text_color, 2)
        cv2.putText(annotated, sub_label,
                    (x1 + 3, y1 - 2),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.4, text_color, 1)

    # ── STEP 4: Show Results ───────────────────────────────
    tiger_count = len(detections)

    if show_result:
        fig, axes = plt.subplots(1, 2, figsize=(20, 8))
        fig.suptitle(f'Tiger Analysis: {filename}',
                     fontsize=14, fontweight='bold')

        # Original image
        axes[0].imshow(original_img_pil) # Display original untouched image
        axes[0].set_title('Original Image')
        axes[0].axis('off')

        # Annotated image
        axes[1].imshow(annotated)
        axes[1].set_title(f'Detection Result — {tiger_count} Tiger(s) Found')
        axes[1].axis('off')

        plt.tight_layout()
        plt.show()

        # Print text summary
        print('\n' + '─' * 50)
        print(f'FILE      : {filename}')
        print(f'TIGERS    : {tiger_count}')
        if quality_issues:
            print(f'QUALITY   : ⚠️  {" | ".join(quality_issues)}')
        else:
            print(f'QUALITY   : ✅ Good')
        print('─' * 50)

        for d in detections:
            vis_icon = {'full': '🐯', 'partial': '🐯½', 'trace': '🐾'}
            print(f'  Tiger {d["tiger_id"]} : {d["display_name"]}')
            print(f'           Visibility   : {vis_icon.get(d["visibility"], "?")} {d["visibility"]}')
            print(f'           Detection    : {d["det_conf"]:.1%} confidence')
            print(f'           Type         : {d["type_conf"]:.1%} confidence')

            # Show top 3 type probabilities
            top3_idx = np.argsort(d['all_probs'])[::-1][:3]
            print(f'           Top 3 types  :')
            for rank, idx in enumerate(top3_idx, 1):
                tname = CLASS_NAMES[idx]
                tprob = d['all_probs'][idx]
                bar   = '█' * int(tprob * 20)
                print(f'             {rank}. {TYPE_DISPLAY_NAMES.get(tname, tname):<20}: {bar:<20} {tprob:.1%}')
        print('─' * 50)

    return {
        'filename'      : filename,
        'tiger_count'   : tiger_count,
        'detections'    : detections,
        'quality_issues': quality_issues,
        'blur_score'    : blur_score,
        'brightness'    : brightness
    }


